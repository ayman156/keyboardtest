    importExportDir.mkdirs();
    new File(importExportDir, "__init__.py").createNewFile();
    
    // 4. إنشاء ملف resources.py الأساسي
    createImportExportResourcesFile();
    
    // 5. إنشاء ملف admin.py محسن مع import_export
    createImportExportAdminFile();
    
    // 6. إنشاء ملف forms.py لاستيراد وتصدير البيانات
    createImportExportFormsFile();
    
    // 7. إنشاء ملف views.py لاستيراد وتصدير البيانات
    createImportExportViewsFile();
    
    // 8. إنشاء ملف urls.py لاستيراد وتصدير البيانات
    createImportExportUrlsFile();
    
    // 9. إنشاء قوالب import_export
    createImportExportTemplates();
    
