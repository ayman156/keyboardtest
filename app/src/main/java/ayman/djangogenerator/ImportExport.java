private void updateAppAdminFilesForImportExport() throws Exception {
    if (!projectData.has("apps")) return;
    
    JSONArray apps = projectData.getJSONArray("apps");
    for (int i = 0; i < apps.length(); i++) {
        updateAppAdminFile(apps.getJSONObject(i));
    }
}

private void updateAppAdminFile(JSONObject app) throws Exception {
    String appName = app.getString("name");
    File adminFile = new File(projectDirectory, appName + "/admin.py");
    
    StringBuilder sb = new StringBuilder();
    sb.append("from django.contrib import admin\n")
      .append("from import_export.admin import ImportExportModelAdmin\n")
      .append("from import_export import resources\n")
      .append("from .models import *\n\n");
    
    if (app.has("models")) {
        JSONArray models = app.getJSONArray("models");
        for (int i = 0; i < models.length(); i++) {
            JSONObject model = models.getJSONObject(i);
            String modelName = model.getString("name");
            String lowerModelName = modelName.toLowerCase();
            
            // إنشاء مورد للاستيراد/التصدير
            sb.append("class ").append(modelName).append("Resource(resources.ModelResource):\n")
              .append("    class Meta:\n")
              .append("        model = ").append(modelName).append("\n")
              .append("        skip_unchanged = True\n")
              .append("        report_skipped = True\n")
              .append("        import_id_fields = ['id']\n\n");
            
            // إنشاء Admin class
            sb.append("@admin.register(").append(modelName).append(")\n")
              .append("class ").append(modelName).append("Admin(ImportExportModelAdmin):\n")
              .append("    resource_class = ").append(modelName).append("Resource\n")
              .append("    list_display = [");
            
            JSONArray fields = model.getJSONArray("fields");
            for (int j = 0; j < Math.min(fields.length(), 5); j++) {
                sb.append("'").append(fields.getJSONObject(j).getString("name")).append("'");
                if (j < Math.min(fields.length(), 5) - 1) sb.append(", ");
            }
            sb.append("]\n")
              .append("    list_filter = ['created_at']\n")
              .append("    search_fields = [");
            
            boolean first = true;
            for (int j = 0; j < fields.length(); j++) {
                JSONObject field = fields.getJSONObject(j);
                String fieldType = field.getString("type");
                
                if (fieldType.equals("CharField") || fieldType.equals("TextField")) {
                    if (!first) sb.append(", ");
                    sb.append("'").append(field.getString("name")).append("'");
                    first = false;
                }
            }
            
            sb.append("]\n")
              .append("    date_hierarchy = 'created_at'\n")
              .append("    ordering = ['-created_at']\n\n");
        }
    }
    
    writeFile(adminFile, sb.toString());
}
    
